import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import { z } from "zod";
import { openApi } from "../apps/api/src/agent-api/spec";

const operation = z.object({
  summary: z.string(),
  parameters: z
    .array(
      z.object({
        name: z.string(),
        in: z.string(),
        required: z.boolean().optional(),
      }),
    )
    .optional(),
  requestBody: z
    .object({
      content: z.object({
        "application/json": z.object({
          schema: z.object({ $ref: z.string() }),
        }),
      }),
    })
    .optional(),
});
export async function renderOwnerApiDocs() {
  const spec = openApi();
  const { paths } = z
    .object({ paths: z.record(z.string(), z.record(z.string(), operation)) })
    .parse(spec);
  const lines = [
    "# Owner API v1 reference",
    "",
    "All paths begin with `/api/v1`. The [quickstart](README.md) explains which credential to use. The [OpenAPI document](openapi.json) contains the full request, response and error schemas.",
    "",
    "| Method | Path | Purpose | Inputs |",
    "| --- | --- | --- | --- |",
  ];
  for (const [path, methods] of Object.entries(paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const inputs = (op.parameters ?? [])
        .filter((p) => p.in !== "path")
        .map(
          (p) =>
            "`" +
            p.name +
            "` (" +
            p.in +
            (p.required ? ", required" : "") +
            ")",
        );
      const body = op.requestBody?.content["application/json"].schema.$ref;
      if (body) inputs.push("`" + body.split("/").at(-1) + "` (JSON body)");
      lines.push(
        "| " +
          [
            method.toUpperCase(),
            "`" + path + "`",
            op.summary,
            inputs.join(", ") || "—",
          ].join(" | ") +
          " |",
      );
    }
  }
  lines.push(
    "",
    "Generated by `pnpm docs:api` from the same contract served by the Worker.",
  );
  const config = await resolveConfig("docs/api/reference.md");
  return {
    "docs/api/openapi.json": await format(JSON.stringify(spec), {
      ...config,
      parser: "json",
    }),
    "docs/api/reference.md": await format(lines.join("\n"), {
      ...config,
      parser: "markdown",
    }),
  };
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  for (const [path, content] of Object.entries(await renderOwnerApiDocs()))
    await writeFile(path, content);
}
